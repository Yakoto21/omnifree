        public static byte[] GetGlyphRows(char c)
        {
            int index = (int)c - 32;
            if (index < 0 || index >= Glyphs.Length)
            {
                // Substituição para caractere não mapeado: bloco '?'
                return Glyphs['?' - 32];
            }
            return Glyphs[index];
        }

        public static bool IsPixelSet(char c, int x, int y)
        {
            if (x < 0 || x >= GlyphWidth || y < 0 || y >= GlyphHeight) return false;
            byte[] rows = GetGlyphRows(c);
            byte rowByte = rows[y];
            // Bit 7 é o pixel mais à esquerda (x = 0)
            int mask = 1 << (7 - x);
            return (rowByte & mask) != 0;
        }
